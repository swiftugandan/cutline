/**
 * A table cell that differs by vehicle width (a slashed value in the CFR).
 * @typedef {{ narrow: number, wide: number }} Split
 * @typedef {number | Split | null} Cell
 */
/** @param {number} narrow @param {number} wide @returns {Split} */
const W = (narrow, wide) => ({ narrow, wide });

/** @param {number} x @param {number} m */
const times = (x, m) => Math.round(x * m * 1000) / 1000;
/** @param {Cell} cell @param {number} m @returns {Cell} */
const scaleCell = (cell, m) => (cell === null ? null : typeof cell === 'number' ? times(cell, m) : W(times(cell.narrow, m), times(cell.wide, m)));

/** @param {string[] | undefined} a @param {string[]} b */
const whenOf = (a, b) => [...(a ?? []), ...b];

/**
 * The entries a cell yields: the unconditional entry (narrow value), and for a slashed cell a wide-vehicle entry that
 * replaces it.
 * @param {string} id @param {Cell} cell @param {(value: number) => Requirement} make @param {string} [slashCite]
 * @returns {Requirement[]}
 */
function byWidth(id, cell, make, slashCite) {
  if (cell === null) return [];
  if (typeof cell === 'number') return [make(cell)];
  const base = make(cell.narrow);
  return [
    { ...base, cite: slashCite ?? base.cite },
    { ...make(cell.wide), id: `${id} (wide)`, when: whenOf(base.when, ['wide']), replaces: base.id, cite: slashCite ?? base.cite },
  ];
}

/**
 * The 750 mm relief: for each entry, a variant measured at 5° down that replaces it when the lamp is mounted low.
 * @param {Requirement[]} entries @param {string} reliefCite
 * @returns {Requirement[]}
 */
function lowVariants(entries, reliefCite) {
  return entries.map(r => {
    /** @type {Requirement} */
    const low = { ...r, id: `${r.id} at 5D (low mounting)`, when: whenOf(r.when, ['low-mounting']), replaces: r.id, cite: `${r.cite}; ${reliefCite}` };
    if (r.kind === 'point') low.v = -5;
    if (r.kind === 'sum' && r.points) low.points = r.points.map((x, i) => (i % 2 === 1 && x < -5 ? -5 : x));
    return low;
  });
}

/**
 * Table VII footnote 6: for each entry at a point marked NO for a side, a note that replaces it for a double-faced
 * lamp on that side.
 * @param {Requirement[]} entries @param {'left' | 'right'} side @param {string} cite
 * @returns {Requirement[]}
 */
function doubleFacedNotes(entries, side, cite) {
  return entries.map(r => ({
    kind: 'note', id: `${r.id}, not required (${side}-side double-faced lamp)`, when: whenOf(r.when, [`double-faced-${side}`]), replaces: r.id,
    text: `Table VII footnote 6: a double-faced turn signal lamp on the ${side} side of a truck tractor need not meet "${r.id}".`, cite,
  }));
}

/**
 * Point and group requirements for a 19-point table.
 * @param {{
 *   mins?: Cell[], maxes?: (number | null)[], groups: Cell[], cite: string, reliefCite: string, slashCite?: string,
 *   multiplier?: number, doubleFaced?: [boolean, boolean][], doubleFacedCite?: string,
 * }} o
 * @returns {Requirement[]}
 */
function grid19(o) {
  const m = o.multiplier ?? 1;
  /** @type {Requirement[]} */
  const out = [];
  /** @param {Requirement[]} entries @param {boolean} relief @param {[boolean, boolean]} [df] */
  const add = (entries, relief, df) => {
    const all = relief ? [...entries, ...lowVariants(entries, o.reliefCite)] : entries;
    out.push(...all);
    if (df && !df[0]) out.push(...doubleFacedNotes(all, 'left', o.doubleFacedCite ?? o.cite));
    if (df && !df[1]) out.push(...doubleFacedNotes(all, 'right', o.doubleFacedCite ?? o.cite));
  };
  GRID19.forEach(([id, h, v, g, relief], i) => {
    const min = o.mins ? scaleCell(o.mins[i] ?? null, m) : null;
    const max = o.maxes ? o.maxes[i] ?? null : null;
    /** @param {number | undefined} value @returns {Requirement} */
    const make = value => {
      /** @type {Requirement} */
      const r = { kind: 'point', id, h, v, group: h === 0 && v === 0 ? 'axis' : 'field', fmvssGroup: g, cite: o.cite };
      if (value !== undefined) r.min = value;
      if (max !== null) r.max = max;
      return r;
    };
    const df = o.doubleFaced ? o.doubleFaced[i] : undefined;
    if (min === null) { if (max !== null) add([make(undefined)], relief, df); return; }
    add(byWidth(id, min, make, o.slashCite), relief, df);
  });
  for (let g = 1; g <= 5; g++) {
    const rows = GRID19.filter(p => p[3] === g);
    const points = rows.flatMap(p => [p[1], p[2]]);
    const relief = rows.some(p => p[4]);
    const sums = byWidth(`Group ${g}`, scaleCell(o.groups[g - 1], m), min => ({ kind: 'sum', id: `Group ${g}`, points, min, group: 'field', fmvssGroup: g, cite: o.cite }), o.slashCite);
    // A double-faced lamp drops a group only when every point in it is marked NO for its side.
    const idx = GRID19.map((p, i) => (p[3] === g ? i : -1)).filter(i => i >= 0);
    const df = o.doubleFaced;
    /** @type {[boolean, boolean] | undefined} */
    const groupDf = df ? [idx.some(i => df[i][0]), idx.some(i => df[i][1])] : undefined;
    add(sums, relief, groupDf);
  }
  return out;
}

/**
 * Ratio requirements: the signal lamp at each point must reach `factor` × the combined lamp's intensity there.
 * @param {(Cell | null)[]} factors one per GRID19 point; null where the table prints "-"
 * @param {string} reference the combined lamp
 * @param {string[]} when CONDITIONS ids under which the ratio applies
 * @param {string} cite
 * @param {{ slashCite?: string, doubleFaced?: [boolean, boolean][], doubleFacedCite?: string }} [o]
 * @returns {Requirement[]}
 */
function ratios(factors, reference, when, cite, o = {}) {
  /** @type {Requirement[]} */
  const out = [];
  GRID19.forEach(([id, h, v], i) => {
    const f = factors[i];
    if (f === null || f === undefined) return;
    const rid = `${id} ratio to ${reference}`;
    /** @param {number} factor @returns {Requirement} */
    const make = factor => ({ kind: 'relative', id: rid, at: { kind: 'point', h, v }, factor, of: 'reference', reference, bound: 'min', group: 'other', when, cite });
    const entries = byWidth(rid, f, make, o.slashCite);
    out.push(...entries);
    const df = o.doubleFaced ? o.doubleFaced[i] : undefined;
    if (df && !df[0]) out.push(...doubleFacedNotes(entries, 'left', o.doubleFacedCite ?? cite));
    if (df && !df[1]) out.push(...doubleFacedNotes(entries, 'right', o.doubleFacedCite ?? cite));
  });
  return out;
}

